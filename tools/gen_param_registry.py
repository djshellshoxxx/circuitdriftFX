#!/usr/bin/env python3
"""Generate src/core/ParameterRegistry.generated.inc from docs/planned-features/parameters.json.
Usage: gen_param_registry.py [--check]   (--check fails if the checked-in file is stale)
"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs/planned-features/parameters.json"
OUT = ROOT / "src/core/ParameterRegistry.generated.inc"
KIND = {"float": "Float", "int": "Int", "bool": "Bool", "enum": "Enum"}
MAP = {"linear": "Linear", "log": "Log"}
SCOPE = {"global": "Global", "a": "SlotA", "b": "SlotB"}

def render():
    d = json.loads(SRC.read_text())
    rows = []
    for p in d["parameters"]:
        rows.append('    {"%s", %d, "%s", ParamKind::%s, %r, %r, %r, "%s", ParamMapping::%s, %r, %s, ParamScope::%s}'
                    % (p["id"], p["hostId"], p["featureId"], KIND[p["type"]], float(p["min"]),
                       float(p["max"]), float(p["default"]), p["unit"], MAP[p["mapping"]],
                       float(p["smoothingMs"]), "true" if p["automatable"] else "false", SCOPE[p["scope"]]))
    return ("// GENERATED by tools/gen_param_registry.py from parameters.json - do not edit.\n"
            + ",\n".join(rows) + "\n")

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("ParameterRegistry.generated.inc is stale; run tools/gen_param_registry.py")
    else:
        OUT.write_text(text)
