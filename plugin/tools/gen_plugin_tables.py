#!/usr/bin/env python3
"""Generate plugin-side tables from docs/planned-features/parameters.json.

  plugin/src/EnumLabels.generated.inc      choice labels for enum parameters
  plugin/tests/ParamIdGolden.generated.inc golden juce::String::hashCode() of every string id

The core registry (src/core) carries no enum label text, so the plugin adapter reads it here.
Usage: gen_plugin_tables.py [--check]   (--check fails if the checked-in files are stale)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/planned-features/parameters.json"
OUT_LABELS = ROOT / "plugin/src/EnumLabels.generated.inc"
OUT_GOLDEN = ROOT / "plugin/tests/ParamIdGolden.generated.inc"
HEADER = "// GENERATED by plugin/tools/gen_plugin_tables.py from parameters.json - do not edit.\n"


def juce_string_hash(text: str) -> int:
    """juce::String::hashCode(): h = 31*h + codepoint over int32 with wrap-around."""
    h = 0
    for ch in text:
        h = (31 * h + ord(ch)) & 0xFFFFFFFF
    return h


def c_str(s: str) -> str:
    assert all(32 <= ord(c) < 127 and c not in '"\\' for c in s), s
    return '"%s"' % s


def render():
    params = json.loads(SRC.read_text())["parameters"]
    pool, spans = [], []
    for p in params:
        if p["type"] != "enum":
            continue
        values = p.get("values")
        count = int(p["max"]) - int(p["min"]) + 1
        if not values or len(values) != count:
            sys.exit("enum %s: 'values' must list exactly %d labels" % (p["id"], count))
        spans.append('    {%s, %d, %d}' % (c_str(p["id"]), len(pool), len(values)))
        pool.extend(c_str(v) for v in values)
    labels = (HEADER + "// Pool of all labels, then one {id, offset, count} span per enum parameter.\n"
              "#define CD_ENUM_LABEL_POOL \\\n    " + ", \\\n    ".join(pool) + "\n"
              "#define CD_ENUM_LABEL_SPANS \\\n" + ", \\\n".join(spans) + "\n")
    rows = ['    {%s, %du, 0x%08Xu}' % (c_str(p["id"]), p["hostId"], juce_string_hash(p["id"])) for p in params]
    golden = (HEADER + "// {string id, registry hostId, juce::String(id).hashCode() as uint32}\n"
              + ",\n".join(rows) + "\n")
    return labels, golden


if __name__ == "__main__":
    labels, golden = render()
    if "--check" in sys.argv:
        if (not OUT_LABELS.exists() or OUT_LABELS.read_text() != labels
                or not OUT_GOLDEN.exists() or OUT_GOLDEN.read_text() != golden):
            sys.exit("plugin generated tables are stale; run plugin/tools/gen_plugin_tables.py")
    else:
        OUT_LABELS.write_text(labels)
        OUT_GOLDEN.write_text(golden)
