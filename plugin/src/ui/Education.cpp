const EducationEntry* findEducation(const juce::String& key) noexcept {
    juce::String k = key;
    if (k.startsWith("slot.a.") || k.startsWith("slot.b.")) k = k.substring(7);
    if (k.startsWith("mod.")) k = "mod";  // sixteen slots per A/B slot share one entry
    for (const auto& e : kEntries)
        if (k == e.key) return &e;
    return nullptr;
}
int educationCount() noexcept { return kEntryCount; }
const EducationEntry& educationAt(int index) noexcept { return kEntries[juce::jlimit(0, kEntryCount - 1, index)]; }

